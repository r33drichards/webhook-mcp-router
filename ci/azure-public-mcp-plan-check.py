"""One existing app activation only; reuse closed-stage contracts without weakening them."""
import copy
import importlib.util
import json
from pathlib import Path

spec = importlib.util.spec_from_file_location('closed', Path(__file__).with_name('azure-disabled-app-plan-check.py'))
closed = importlib.util.module_from_spec(spec)
spec.loader.exec_module(closed)
APP = 'azapi_resource.app[0]'
DIGEST = '2c286c45033558bae23798247249411bb080aabba1fd710751e47878e791782c'

def present(value):
    if isinstance(value, dict): return any(present(v) for v in value.values())
    if isinstance(value, list): return any(present(v) for v in value)
    return value is not False and value is not None

def project(value, public):
    value = copy.deepcopy(value)
    props = value['body']['properties']
    site = props['siteConfig']
    expected = (True, 'Enabled', 'Allow') if public else (False, 'Disabled', 'Deny')
    actual = (props['enabled'], props['publicNetworkAccess'], site['ipSecurityRestrictionsDefaultAction'])
    if not closed.base.exact(actual, expected): raise ValueError('ACTIVATION_STATE')
    props['enabled'] = False
    props['publicNetworkAccess'] = 'Disabled'
    site['ipSecurityRestrictionsDefaultAction'] = 'Deny'
    return value

def validate(plan, require_noop=False):
    closed.reject_write_only(plan)
    rows = plan.get('resource_changes', [])
    apps = [r for r in rows if r.get('address') == APP]
    if len(apps) != 1: raise ValueError('APP_REQUIRED')
    change = apps[0]['change']
    actions = change['actions']
    if actions not in (['update'], ['no-op']): raise ValueError('EXISTING_APP_ONLY')
    if require_noop and any(r['change']['actions'] != ['no-op'] for r in rows): raise ValueError('POST_APPLY_DRIFT')
    # Only the provider's computed output may be unknown, never body/identity or overrides.
    unknown = copy.deepcopy(change.get('after_unknown', {}))
    if not isinstance(unknown, dict): raise ValueError('UNKNOWN_INPUT')
    unknown.pop('output', None)
    if present(unknown): raise ValueError('UNKNOWN_INPUT')
    before = project(change['before'], public=actions == ['no-op'])
    after = project(change['after'], public=True)
    # An update may only change enabled/PNA/main-site default action. Computed output
    # is regenerated by AzAPI and is not an applied input.
    def inputs(value):
        value = copy.deepcopy(value)
        value.pop('output', None)
        return value
    if not closed.base.exact(inputs(before), inputs(after)): raise ValueError('UNAPPROVED_APP_DELTA')
    for snapshot in (before, after):
        projected = copy.deepcopy(plan)
        row = next(r for r in projected['resource_changes'] if r['address'] == APP)
        row['change']['actions'] = ['no-op']
        row['change']['after'] = snapshot
        if closed.validate(projected, DIGEST) != 13: raise ValueError('INVENTORY')
    # Output changes cannot introduce another write/action channel.
    if any(c.get('actions') != ['no-op'] for c in plan.get('output_changes', {}).values()):
        raise ValueError('OUTPUT_CHANGE')
    return 13

if __name__ == '__main__':
    import argparse
    parser = argparse.ArgumentParser()
    parser.add_argument('plan')
    parser.add_argument('--require-noop', action='store_true')
    args = parser.parse_args()
    try:
        validate(json.loads(Path(args.plan).read_text()), args.require_noop)
        print('PASS public authenticated MCP plan; resources=13; SQL closed; dispatch disabled')
    except Exception:
        # Never print raw plan data or exception messages.
        print('FAIL PUBLIC_MCP_PLAN_REJECTED')
        raise SystemExit(1)
